void Lqr::Calc()
{
    if (this->F_N_ != -1 && this->F_N_ < 110.0f) {
        for (uint8_t i = 0; i < 4; i++)
            for (uint8_t j = 0; j < 10; j++) {
                if (i == 2 || i == 3) {
                    if (j < 4 || j > 7) K_[i][j] = 0;
                    else{
                        K_[i][j] *=1.2 ;
                    }
                } else
                    K_[i][j] = 0;
            }
    } else {

        float l_l_square = l_l * l_l, l_r_square = l_r * l_r, l_l_cube = l_l * l_l * l_l, l_r_cube = l_r * l_r * l_r;

        for (uint8_t i = 0; i < 4; i++)
            for (uint8_t j = 0; j < 10; j++) {
                int index    = i * 10 + j;
                K_[i][j]     = arg[index][0] * l_l_square + arg[index][1] * l_r_square + arg[index][2] * l_l * l_r + arg[index][3] * l_l + arg[index][4] * l_r + arg[index][5];
                K_show[i][j] = K_[i][j];
            }
    }

    K_[0][8] /= t, K_[0][9] /= t, K_[1][8] /= t, K_[1][9] /= t;

    for (uint8_t i = 0; i < 4; i++) {
        T_[i] = -(K_[i][0] * (s - target_s)*0.5 +
                  K_[i][1] * (s_dot - target_s_dot)*2.5 +
                  K_[i][2] * (phi - target_phi)*0.9*0.9 +
                  K_[i][3] * (phi_dot - target_phi_dot)*0.9*0.9 +
                  K_[i][4] * (theta_ll - target_theta_ll)*3.1 +
                  K_[i][5] * (theta_ll_dot - target_theta_ll_dot)*2.0 +
                  K_[i][6] * (theta_lr - target_theta_lr)*3.1 +
                  K_[i][7] * (theta_lr_dot - target_theta_lr_dot)*2.0 +
                  K_[i][8] * (theta_b - target_theta_b)*0.8 +
                  K_[i][9] * (theta_b_dot - target_theta_b_dot))*1.8;

        Txx[i][0] = K_[i][0] * (s - target_s)*1.2;
        Txx[i][1] = K_[i][1] * (s_dot - target_s_dot)*1.5;
        Txx[i][2] = K_[i][2] * (phi - target_phi)*0.9*0.9;
        Txx[i][3] = K_[i][3] * (phi_dot - target_phi_dot)*0.9*0.9;
        Txx[i][4] = K_[i][4] * (theta_ll - target_theta_ll)*1.85;
        Txx[i][5] = K_[i][5] * (theta_ll_dot - target_theta_ll_dot)*2.0;
        Txx[i][6] = K_[i][6] * (theta_lr - target_theta_lr)*1.85;
        Txx[i][7] = K_[i][7] * (theta_lr_dot - target_theta_lr_dot)*2.0;
        Txx[i][8] = K_[i][8] * (theta_b - target_theta_b)*0.8;
        Txx[i][9] = K_[i][9] * (theta_b_dot - target_theta_b_dot);
    }
    T_[0]*=0.4;
    T_[1]*=0.4;
}